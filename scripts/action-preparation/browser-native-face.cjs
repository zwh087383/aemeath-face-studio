async page => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.waitForFunction(() => window.nativeBehaviorLab?.snapshot().ready && window.nativeBehaviorLab?.faceSnapshot, null, { timeout: 180000 });
  const result = await page.evaluate(async () => {
    const api = window.nativeBehaviorLab, checks = [];
    const check = (name, passed, detail = {}) => checks.push({ name, passed: Boolean(passed), ...detail });
    const data = await fetch('/face-preparation-data/playback.json').then(response => response.json());
    const weights = () => Array.from(api.mesh.morphTargetInfluences);
    const bones = () => { api.mesh.updateMatrixWorld(true); return api.mesh.skeleton.bones.flatMap(bone => bone.matrixWorld.toArray()); };
    const maximum = (a, b) => Math.max(0, ...a.map((value, i) => Math.abs(value - b[i])));
    api.setManualClock(true); api.pause(false);
    document.getElementById('joint-face').checked = false;
    const group = api.groups.find(row => row.name === 'Talk02'); await api.select(group.id);
    api.restart(); api.step(.6); const bodyOnly = bones();
    document.getElementById('face-recipe').value = 'authored-expression:surprise';
    document.getElementById('joint-face').checked = true; api.restart();
    const firstOwner = api.faceSnapshot().active?.owner;
    check('body start starts the manually selected expression', firstOwner?.source === 'native-behavior-preview');
    api.step(.6); const faceOn = weights(), withFace = bones();
    check('expression changes actual PMX morph weights', faceOn.some(value => Math.abs(value) > .001));
    const boneError = maximum(bodyOnly, withFace);
    check('expression does not change actual body bone matrices', boneError < 1e-10, { maximumError: boneError });
    const frozen = api.faceSnapshot(); api.pause(true); api.step(.7);
    const paused = api.faceSnapshot();
    check('pause preserves face value and velocity exactly', frozen.time === paused.time && maximum(frozen.expressionWeights, paused.expressionWeights) === 0 && maximum(frozen.velocity, paused.velocity) === 0 && JSON.stringify(frozen.active) === JSON.stringify(paused.active));
    api.pause(false); document.getElementById('face-speech').checked = true; api.step(0);
    const speaking = weights(), lip = { 52: .26, 53: .12 };
    check('all actual pronunciation leaves belong to lip layer', data.mouthIndices.every(index => speaking[index] === (lip[index] ?? 0)), { mouthLeaves: data.mouthIndices.length });
    document.getElementById('face-speech').checked = false; api.step(0);
    const cancelBefore = api.faceSnapshot(), cancelled = api.cancel(false), cancelAfter = api.faceSnapshot();
    check('body cancellation retires the same face owner', cancelled.accepted && cancelAfter.active === null);
    check('cancelling preserves current face value and velocity', maximum(cancelBefore.expressionWeights, cancelAfter.expressionWeights) === 0 && maximum(cancelBefore.velocity, cancelAfter.velocity) === 0);
    api.step(2); const returned = api.faceSnapshot();
    check('cancelled expression returns to supplied neutral base', Math.max(...returned.expressionWeights.map(Math.abs)) < 1e-8);
    api.restart(); const newOwner = api.faceSnapshot().active?.owner;
    check('restart uses a new owner generation', newOwner?.generation > firstOwner.generation);
    api.step(.2); const beforeSwitch = api.player.pose().map(row => ({ p: row.p.toArray(), q: row.q.toArray(), s: row.s.toArray() }));
    const next = api.groups.find(row => row.name === 'Talk03') ?? api.groups.find(row => row.id !== group.id);
    await api.select(next.id);
    const afterSwitch = api.player.pose().map(row => ({ p: row.p.toArray(), q: row.q.toArray(), s: row.s.toArray() }));
    const flatten = pose => pose.flatMap(row => [...row.p, ...row.q, ...row.s]);
    const entryError = maximum(flatten(beforeSwitch), flatten(afterSwitch));
    check('loaded group starts at current displayed pose', entryError < 1e-12, { maximumError: entryError });
    api.step(.6); api.pause(true); api.setView('angle');
    check('every matrix and morph remains finite', [...bones(), ...weights()].every(Number.isFinite));
    check('automatic use remains unapproved', api.snapshot().automaticEligible === false);
    return { checks, passed: checks.every(row => row.passed), scope: 'Real PMX bone matrices, morph ownership and shared cancellation in a manually selected local preview. Asset loading freezes the old frame; not a claim of uninterrupted loading, semantic selection, real speech or physics.' };
  });
  await page.screenshot({ path: 'outputs/action-execution-preparation-20261023/native-face-linked.png' });
  return { ...result, errors, passed: result.passed && !errors.length };
}
